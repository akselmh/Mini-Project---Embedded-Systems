typedef ap_axiu<32,0,0,0> AxiStream32;

// send one image to the AXI-stream
int run_image(float img[n_inputs]) {
    hls::stream<AxiStream32> in_stream;
    hls::stream<AxiStream32> out_stream;

    // Push all pixels into INPUT stream
    for (int i = 0; i < n_inputs; ++i) {
        AxiStream32 word;

        union { float f; uint32_t i; } conv;
        conv.f = img[i];

        word.data = conv.i;  
        word.keep = -1;    
        word.strb = -1;
        word.user = 0;
        word.id   = 0;
        word.dest = 0;
        word.last = (i == n_inputs - 1); 

        in_stream.write(word);
    }

    // call func
    nn_inference(in_stream, out_stream);

    // read single prediction word from OUTPUT
    AxiStream32 out_word = out_stream.read();
    int pred = (int)out_word.data;

    return pred;
}

